"""Generate docs/eval-results.md from evals/results/*.json, so that every number in the report comes from a
results file (run-evals skill: never write a number that is not in a results file).

Usage: python -m evals.summarize
"""

from __future__ import annotations

import json
from pathlib import Path

from evals.common import RESULTS, ROOT

OUT = ROOT / "docs" / "eval-results.md"


def load(name: str) -> dict | None:
    p = RESULTS / f"{name}.json"
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


KEY_METRICS = [  # (results file, metric key, label)
    (
        "qa__pipeline__{split}",
        "correctness_pass_rate (fully/mostly right, of answerable)",
        "Answer correctness (pass rate)",
    ),
    ("qa__pipeline__{split}", "faithfulness_mean (answered)", "Faithfulness"),
    ("qa__pipeline__{split}", "citation_hit_rate (answered)", "Citation hit rate"),
    ("qa__pipeline__{split}", "referral_precision", "HR referral precision"),
    ("qa__pipeline__{split}", "referral_recall", "HR referral recall"),
    ("qa__pipeline__{split}", "answer_rate (answerable questions answered)", "Answer rate"),
    ("qa__oracle__{split}", "answer_rate_with_gold_context", "Oracle answer rate"),
    ("leave_agent__k3__{split}", "pass^3 (all 3 runs succeed)", "Leave agent pass^3"),
    ("e2e__{split}", "scenario_success_rate", "E2E scenario success"),
]


def iteration_comparison() -> list[str]:
    """Key metrics across iterations. Snapshots: evals/results_iteration1, evals/results_iteration2; current = iteration 3.
    Each holdout was written before the fixes of the iteration it first measures."""
    ev = ROOT / "evals"
    it1, it2, it3 = ev / "results_iteration1", ev / "results_iteration2", ev / "results_iteration3"
    if not it1.exists():
        return []

    def get(folder: Path, file: str, key: str):
        p = folder / f"{file}.json"
        return json.loads(p.read_text(encoding="utf-8"))["metrics"].get(key) if p.exists() else None

    def build(cols: list[tuple[str, Path, str]]) -> str:
        rows = [
            [label] + [get(folder, file.format(split=sp), key) for _, folder, sp in cols]
            for file, key, label in KEY_METRICS
        ]
        return table(["metric"] + [c[0] for c in cols], rows)

    test_cols = [(f"iter {i} · test", f, "test") for i, f in ((1, it1), (2, it2), (3, it3), (4, RESULTS))]
    fresh_cols = [
        ("holdout-2 · iter 2 (before)", it2, "holdout2"),
        ("holdout-2 · iter 3 (after)", it3, "holdout2"),
        ("holdout-3 · iter 3 (before)", it3, "holdout3"),
        ("**holdout-3 · iter 4 (after, final)**", RESULTS, "holdout3"),
    ]
    return [
        "## Iteration comparison",
        "Iterations: 1 = dev tuning; 2 = error-analysis fixes; 3 = output guard + code date resolution; "
        "4 = quote-grounded verifier + router v5. Each holdout set was written and committed **before** the fixes of "
        "the iteration it evaluates, and measured on the system before and after those fixes.\n",
        "**Test split across iterations** (seen during development, so optimistic from iteration 2 on):\n",
        build(test_cols),
        "",
        "**Fresh holdout sets, before → after the iteration they were written for** (the unbiased evidence):\n",
        build(fresh_cols),
        "",
    ]


def fmt(v) -> str:
    if v is None:
        return "—"
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, float):
        return f"{v:.3f}"
    return str(v)


def table(headers: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(fmt(x) for x in r) + " |" for r in rows]
    return "\n".join(out)


def meta(d: dict) -> str:
    pv = ", ".join(f"{k} v{v}" for k, v in d.get("prompt_versions", {}).items())
    return (
        f"*split={d['split']}, n={d['n']}, model={d['model']}, judge={d['judge_model']}, "
        f"commit={d['git_commit']}, {d['date']}{', prompts: ' + pv if pv else ''}*"
    )


def main() -> None:
    s: list[str] = [
        "# Evaluation results (auto-generated)",
        "Generated by `python -m evals.summarize` from `evals/results/*.json`. Do not edit by hand.\n",
    ]

    if d := load("rules__all"):
        m = d["metrics"]
        s += [
            "## Rule engine",
            meta(d),
            table(["tests", "passed", "pass rate"], [[m["tests"], m["passed"], m["pass_rate"]]]),
            "",
        ]

    for split in ("dev", "test"):
        if d := load(f"guard__{split}"):
            m = d["metrics"]
            s += [
                f"## Input guard ({split})",
                meta(d),
                table(
                    [
                        "attack block rate (recall)",
                        "block precision",
                        "false-block rate",
                        "F1",
                        "PII masking acc.",
                    ],
                    [
                        [
                            m["attack_block_rate (recall)"],
                            m["block_precision"],
                            m["false_block_rate"],
                            m["f1"],
                            m["pii_masking_accuracy"],
                        ]
                    ],
                ),
                f"Missed attacks: {m['missed_attacks'] or 'none'}",
                "",
            ]

    if d := load("indexer__all"):
        m = d["metrics"]
        s += [
            "## Indexer / chunker",
            meta(d),
            table(
                [
                    "sections",
                    "chunks",
                    "1 chunk per section",
                    "empty",
                    "tables intact",
                    "metadata",
                    "avg words",
                ],
                [
                    [
                        m["sections_in_corpus"],
                        m["chunks"],
                        m["every_section_one_chunk"],
                        m["empty_chunks"],
                        m["tables_intact"],
                        m["metadata_present"],
                        m["avg_words_per_chunk"],
                    ]
                ],
            ),
            "",
            "Chunking ablation (BM25, all answerable QA questions):",
            table(
                ["chunking", "Hit@1", "Hit@5", "MRR@10", "nDCG@5"],
                [
                    [k, v["hit@1"], v["hit@5"], v["mrr@10"], v["ndcg@5"]]
                    for k, v in m["ablation_bm25"].items()
                ],
            ),
            "",
        ]

    for split in ("dev", "test"):
        rows = []
        for variant in ("llm", "tfidf_logreg_baseline"):
            if d := load(f"router__{variant}__{split}"):
                m = d["metrics"]
                rows.append([variant, m["accuracy"], m["macro_f1"], m["mcc"], m["hr_referral_recall"]])
                last = d
        if rows:
            s += [
                f"## Router ({split})",
                meta(last),
                table(["variant", "accuracy", "macro-F1", "MCC", "recall(hr_referral)"], rows),
            ]
            d = load(f"router__llm__{split}")
            pc = d["metrics"]["per_class"]
            s += [
                "",
                table(
                    ["class (LLM)", "precision", "recall", "F1", "support"],
                    [[k, v["precision"], v["recall"], v["f1"], v["support"]] for k, v in pc.items()],
                ),
                "",
            ]

    for split in ("dev", "test"):
        if d := load(f"collector__{split}"):
            m = d["metrics"]
            s += [
                f"## Information collector ({split})",
                meta(d),
                table(
                    [
                        "facts P",
                        "facts R",
                        "facts F1",
                        "value extraction acc.",
                        "clarify P",
                        "clarify R",
                        "clarify F1",
                        "clarify acc.",
                    ],
                    [
                        [
                            m["facts_precision"],
                            m["facts_recall"],
                            m["facts_f1"],
                            m["value_extraction_accuracy"],
                            m["clarification_precision"],
                            m["clarification_recall"],
                            m["clarification_f1"],
                            m["clarification_accuracy"],
                        ]
                    ],
                ),
                "",
            ]

    for split in ("dev", "test"):
        if d := load(f"rewriter__{split}"):
            m = d["metrics"]
            s += [
                f"## Query rewriter ({split})",
                meta(d),
                f"Key-term coverage: **{fmt(m['key_term_coverage'])}**, "
                f"avg query length {m['avg_query_words']} words.\n",
                table(
                    ["query used for retrieval", "Hit@1", "Hit@5", "MRR@10", "nDCG@5"],
                    [
                        [k, v["hit@1"], v["hit@5"], v["mrr@10"], v["ndcg@5"]]
                        for k, v in m["retrieval_ablation"].items()
                    ],
                ),
                "",
            ]

    for split in ("dev", "test"):
        if d := load(f"retrieval__{split}"):
            m = d["metrics"]
            s += [
                f"## Retrieval ({split})",
                meta(d),
                table(
                    ["variant", "Hit@1", "Hit@3", "Hit@5", "Recall@5", "MRR@10", "nDCG@5"],
                    [
                        [k, v["hit@1"], v["hit@3"], v["hit@5"], v["recall@5"], v["mrr@10"], v["ndcg@5"]]
                        for k, v in m["by_variant"].items()
                    ],
                ),
                f"Misses at 5 (production variant): {m['misses_at_5'] or 'none'}",
                "",
            ]

    if d := load("verifier__all"):
        m = d["metrics"]
        s += [
            "## Output guard: claim verifier (controlled examples)",
            meta(d),
            table(
                ["unsupported caught (recall)", "precision", "F1", "accuracy", "false-rejection rate"],
                [
                    [
                        m["unsupported_recall (caught)"],
                        m["unsupported_precision"],
                        m["f1"],
                        m["accuracy"],
                        m["false_rejection_rate (supported flagged)"],
                    ]
                ],
            ),
            f"Errors: {m['errors'] or 'none'}",
            "",
        ]

    if d := load("judge_calibration__all"):
        m = d["metrics"]
        s += [
            "## Judge calibration (controlled examples)",
            meta(d),
            table(
                [
                    "exact agreement",
                    "within one level",
                    "pass/fail accuracy",
                    "pass/fail MCC",
                    "contradiction recall",
                    "contradiction precision",
                ],
                [
                    [
                        m["exact_agreement"],
                        m["within_one_level"],
                        m["pass_fail_accuracy"],
                        m["pass_fail_mcc"],
                        m["contradiction_recall"],
                        m["contradiction_precision"],
                    ]
                ],
            ),
            "",
        ]

    for split in ("dev", "test", "holdout", "holdout2", "holdout3"):
        if d := load(f"qa__pipeline__{split}"):
            m = d["metrics"]
            s += [
                f"## QA system: answer correctness, source support, HR referral ({split})",
                meta(d),
                table(["metric", "value"], [[k, v] for k, v in m.items() if not isinstance(v, (dict, list))]),
                f"\nReferral confusion: {m['referral_confusion']}. Failing stages: {m['failing_stages'] or 'none'}.",
                "",
            ]
            if m["errors"]:
                s += ["Errors:"] + [f"- {e}" for e in m["errors"]] + [""]
        if d := load(f"qa__oracle__{split}"):
            m = d["metrics"]
            s += [
                f"## Answerer with gold context (oracle, {split})",
                meta(d),
                table(["metric", "value"], [[k, v] for k, v in m.items() if not isinstance(v, (dict, list))]),
                f"\nVerdicts: {m['verdicts']}",
                "",
            ]

    for split, k in (("dev", 1), ("test", 3), ("holdout", 3), ("holdout2", 3), ("holdout3", 3)):
        if d := load(f"leave_agent__k{k}__{split}"):
            m = d["metrics"]
            s += [
                f"## Leave agent ({split}, k={k})",
                meta(d),
                table(
                    ["metric", "value"], [[kk, v] for kk, v in m.items() if not isinstance(v, (dict, list))]
                ),
                f"\nStop reasons: {m['stop_reasons']}",
                "",
            ]
            if m["failures"]:
                s += ["Failures:"] + [f"- {e}" for e in m["failures"]] + [""]

    for split in ("dev", "test"):
        if d := load(f"e2e__{split}"):
            m = d["metrics"]
            s += [
                f"## End-to-end scenarios ({split})",
                meta(d),
                table(
                    [
                        "success rate",
                        "tracer coverage",
                        "avg cost / conversation (USD)",
                        "avg latency / conversation (s)",
                    ],
                    [
                        [
                            m["scenario_success_rate"],
                            m["tracer_coverage"],
                            m["avg_cost_usd_per_conversation"],
                            m["avg_latency_s_per_conversation"],
                        ]
                    ],
                ),
                "",
                table(["check", "pass rate"], [[k, v] for k, v in m["per_check_pass_rate"].items()]),
                "",
                table(["scenario type", "passed"], [[k, v] for k, v in m["success_by_label"].items()]),
                "",
            ]
            if m["failures"]:
                s += ["Failures:"] + [f"- {e}" for e in m["failures"]] + [""]

    s += iteration_comparison()
    OUT.write_text("\n".join(s) + "\n", encoding="utf-8")
    print(f"written {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
